//! Whole-schema statistics and the generated `codegen/report.txt`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::emit::Ctx;
use crate::lower;
use crate::model::{ContentModel, Diagnostics, Model, type_part};

#[derive(Debug, Default, PartialEq, Eq)]
pub struct Stats {
    /// Entries carrying their own particle (`slottable.py`'s population).
    pub total: usize,
    pub single_qname_only: usize,
    pub multi_qname: usize,
    pub unsupported: BTreeMap<&'static str, usize>,
    pub ambiguous: usize,
    pub ecma_disagreements: Vec<String>,
    /// SDK attribute entries joined to an XSD default (`join3.py`).
    pub joined_defaults: usize,
    /// Joined defaults outside the SDK type's lexical space (dropped).
    pub default_mismatches: usize,
    pub sdk_attributes: usize,
}

impl Stats {
    pub fn unsupported_total(&self) -> usize {
        self.unsupported.values().sum()
    }
}

/// Lowering over the raw SDK particles (no overrides), as `slottable.py`
/// does, plus the namespace-correct default join of `join3.py`.
pub fn compute(model: &Model<'_>) -> Stats {
    let mut st = Stats::default();
    let xsd_ns = model.xsd.namespaces();
    let mut d = Diagnostics::default();
    for (_, f) in &model.sdk.files {
        for (ti, t) in f.types.iter().enumerate() {
            // defaults
            let fi = model.index[&t.name].0;
            let _ = ti;
            for a in &t.attributes {
                st.sdk_attributes += 1;
                let Some((p, ctn)) = type_part(&t.name).split_once(':') else { continue };
                let Some(ns) = model.sdk.prefixes.get(p) else { continue };
                if !xsd_ns.contains(ns.as_str()) || !model.xsd.cts.contains_key(&(ns.clone(), ctn.to_owned())) {
                    continue;
                }
                let Some((ans, al, _)) = model.resolve_qname(&a.qname) else { continue };
                if let Some(def) = model.xsd_default(&t.name, &ans, &al) {
                    st.joined_defaults += 1;
                    let ty = model.map_type(&a.ty, fi, &mut d, &t.name);
                    if !model.default_fits(&ty, &def) {
                        st.default_mismatches += 1;
                    }
                }
            }
            // lowering
            let Some(p) = &t.particle else { continue };
            st.total += 1;
            match lower::lower(p, false) {
                Err(e) => *st.unsupported.entry(e.text()).or_default() += 1,
                Ok(sl) => {
                    if lower::has_ambiguous(&sl) {
                        st.ambiguous += 1;
                    }
                    if sl.iter().all(|s| s.names.len() == 1) {
                        st.single_qname_only += 1;
                    } else {
                        st.multi_qname += 1;
                    }
                    if let Some((a, b)) = lower::ecma_disagreement(&t.name, &sl, model.xsd, &model.sdk.prefixes) {
                        st.ecma_disagreements.push(format!("{} ({a}, {b})", t.name));
                    }
                }
            }
        }
    }
    st
}

pub fn report(st: &Stats, diags: &Diagnostics, ctx: &Ctx<'_, '_>) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# @generated by cargo xtask codegen — do not edit");
    let _ = writeln!(out, "# Review this file's diff together with the generated code (ADR-0002 §2).\n");
    let _ = writeln!(out, "## Slot lowering (raw SDK particles, ADR-0002 §4.1)");
    let _ = writeln!(
        out,
        "content models {}: single-QName slots only {}, multi-QName slots {} ({} with a QName in two slots), unsupported {} {:?}",
        st.total,
        st.single_qname_only,
        st.multi_qname,
        st.ambiguous,
        st.unsupported_total(),
        st.unsupported
    );
    let _ = writeln!(out, "SDK slots permit an order the ECMA XSD forbids: {}", st.ecma_disagreements.len());
    for e in &st.ecma_disagreements {
        let _ = writeln!(out, "  {e}");
    }
    let _ = writeln!(out, "\n## Attribute defaults (ADR-0002 §1.2)");
    let _ = writeln!(
        out,
        "SDK attribute entries {}, joined to an XSD default {}, dropped as DefaultMismatch {}",
        st.sdk_attributes, st.joined_defaults, st.default_mismatches
    );
    let _ = writeln!(out, "\n## Allowlisted entries");
    for (name, (a, e)) in &ctx.entries {
        let content = match &e.content {
            ContentModel::Empty => "empty".to_owned(),
            ContentModel::Text(_) => "text".to_owned(),
            ContentModel::Slots(s) => format!("{} slots", s.len()),
            ContentModel::Unsupported { reason, .. } => format!("unsupported: {reason}"),
        };
        let _ = writeln!(
            out,
            "  [{}] {:?} {name} -> {} ({content}, {} attrs{})",
            a.group,
            a.access,
            ctx.type_names[name],
            e.attrs.len(),
            if e.attrs_incomplete { ", attrs_incomplete" } else { "" }
        );
    }
    let lines: BTreeSet<&String> = diags.lines.iter().collect();
    let mut kinds: BTreeMap<&str, usize> = BTreeMap::new();
    for l in &lines {
        *kinds.entry(l.split(' ').next().unwrap_or_default()).or_default() += 1;
    }
    let _ = writeln!(out, "\n## Diagnostics ({} total: {:?})", lines.len(), kinds);
    for l in lines {
        let _ = writeln!(out, "{l}");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The generator's lowering must reproduce `spikes/adr-0002/py/slottable.py`
    /// (ADR-0002 §4.1: 1,573 / 537 / 12 unsupported, 1 ambiguous, 8 ECMA
    /// disagreements) and `join3.py` (1,511 joined defaults).
    #[test]
    fn lowering_totals_match_slottable_py() {
        let root = crate::root();
        let sdk = crate::sdk::Sdk::load(&root.join(crate::SDK_DIR)).unwrap();
        let xsd = crate::xsd::Xsd::load(&root.join(crate::XSD_DIR)).unwrap();
        let mut d = Diagnostics::default();
        let model = Model::new(&sdk, &xsd, &[], &mut d);
        let st = compute(&model);
        assert_eq!(st.total, 2122);
        assert_eq!(st.single_qname_only, 1573);
        assert_eq!(st.multi_qname, 537);
        assert_eq!(st.unsupported_total(), 12);
        assert_eq!(st.unsupported.get("exclusive choice of repeating alternatives"), Some(&4));
        assert_eq!(st.unsupported.get("multi-slot alternative"), Some(&8));
        assert_eq!(st.ambiguous, 1);
        assert_eq!(st.ecma_disagreements.len(), 8, "{:#?}", st.ecma_disagreements);
        assert_eq!(st.sdk_attributes, 8510);
        assert_eq!(st.joined_defaults, 1511);
    }
}

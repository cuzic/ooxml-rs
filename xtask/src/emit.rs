//! Rust source emission for `ooxml-schema` (ADR-0002 §3) and the parts
//! table in `ooxml-core` (§6). Output is plain text, formatted by the pinned
//! `prettyplease`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::Res;
use crate::config::{Access, Allowed, GROUPS};
use crate::lower::{ANY, LSlot};

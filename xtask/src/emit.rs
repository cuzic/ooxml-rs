pub const HEADER: &str = "// @generated by cargo xtask codegen — do not edit\n";

/// Markers renamed by the `Element` suffix rule (`group::Name`). Pinned so
/// that an allowlist change cannot rename a public type silently.
const ELEMENT_SUFFIXED: &[&str] = &["sml::SheetViewElement", "sml::WorkbookViewElement"];

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
    "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box",
    "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

pub fn pascal(s: &str) -> String {
    let mut out = String::new();
    for seg in s.split(|c: char| !c.is_ascii_alphanumeric()).filter(|s| !s.is_empty()) {
        let mut cs = seg.chars();
        if let Some(f) = cs.next() {
            out.push(f.to_ascii_uppercase());
            out.extend(cs);
        }
    }
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'V');
    }
    out
}

pub fn snake(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !out.ends_with('_') && !out.is_empty() {
                out.push('_');
            }
            continue;
        }
        if c.is_ascii_uppercase() && i > 0 {
            let prev = chars[i - 1];
            let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            if (prev.is_ascii_lowercase() || prev.is_ascii_digit() || (prev.is_ascii_uppercase() && next_lower))
                && !out.ends_with('_')
            {
                out.push('_');
            }
        }
        out.push(c.to_ascii_lowercase());
    }
    let mut out = out.trim_matches('_').to_owned();
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert_str(0, "v_");
    }
    out
}

/// Escapes a Rust keyword by appending `_`.
fn ident(s: &str) -> String {
    if KEYWORDS.contains(&s) { format!("{s}_") } else { s.to_owned() }
}

fn upper(s: &str) -> String {
    snake(s).trim_end_matches('_').to_ascii_uppercase()
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn doc(out: &mut String, text: &str) {
    for line in text.lines() {
        let _ = writeln!(out, "#[doc = {}]", lit(&format!(" {line}")));
    }
}

/// Method-name registry for one view type.
struct Names(BTreeSet<String>);

impl Names {
    fn new(reserved: &[&str]) -> Self {
        Names(reserved.iter().map(|s| (*s).to_owned()).collect())
    }
    /// Claims a unique method name (keyword-escaped).
    fn claim(&mut self, base: &str, suffix: &str) -> String {
        let mut n = ident(base);
        while self.0.contains(&n) {
            n.push_str(suffix);
        }
        self.0.insert(n.clone());
        n
    }
}

struct TyInfo {
    rust: String,
    parse: Option<&'static str>,
    format: Fmt,
}

enum Fmt {
    Str,
    Static(&'static str),
    With(&'static str),
    Float(bool),
    Enum,
}

pub struct Ctx<'m, 'a> {
    pub model: &'m Model<'a>,
    /// SDK Name → (group, access, entry)
    pub entries: BTreeMap<String, (Allowed, Entry)>,
    /// SDK Name → Rust marker name
    pub type_names: BTreeMap<String, String>,
    /// (group, enum at) → Rust enum name
    pub enum_names: BTreeMap<(&'static str, (usize, usize)), String>,
    /// `[detach] unique_attrs`, resolved: (element `prefix:local`, attribute
    /// `(ns, prefix, local)`, XSD default), for every SDK entry of the type.
    pub unique_attrs: Vec<UniqueAttrSpec>,
}

/// A resolved `[detach] unique_attrs` entry: element `prefix:local`,
/// attribute `(ns, prefix, local)`, XSD default.
pub type UniqueAttrSpec = (String, (String, String, String), Option<String>);

impl<'m, 'a> Ctx<'m, 'a> {
    pub fn new(model: &'m Model<'a>, allow: &BTreeMap<String, Allowed>, unique: &[String], diags: &mut Diagnostics) -> Res<Self> {
        let mut unique_attrs = Vec::new();
        for u in unique {
            let (ct, attr) = u.split_once('@').ok_or_else(|| format!("unique_attrs entry {u:?}: expected \"<complex type>@<attribute>\""))?;
            let prefix = format!("{ct}/");
            let mut n = 0;
            // concrete entries only (`<type>/` is the abstract one)
            for name in model.index.keys().filter(|k| k.starts_with(&prefix) && k.len() > prefix.len()) {
                let e = model.resolve(name, diags).ok_or_else(|| format!("unique_attrs: {name} does not resolve"))?;
                let a = e.attrs.iter().find(|a| a.local == attr && a.ns.is_empty() || format!("{}:{}", a.prefix, a.local) == attr)
                    .ok_or_else(|| format!("unique_attrs entry {u:?}: {name} has no attribute {attr}"))?;
                unique_attrs.push((format!("{}:{}", e.prefix, e.local), (a.ns.clone(), a.prefix.clone(), a.local.clone()), a.default.clone()));
                n += 1;
            }
            if n == 0 {
                return Err(format!("unique_attrs entry {u:?}: no SDK entry of type {ct}").into());
            }
        }
        let mut entries = BTreeMap::new();
        for (name, a) in allow {
            let e = model.resolve(name, diags).ok_or_else(|| format!("allowlisted {name:?} is not in the SDK data"))?;
            entries.insert(name.clone(), (a.clone(), e));
        }
        let mut type_names = BTreeMap::new();
        let mut enum_names = BTreeMap::new();
        let mut suffixed: BTreeSet<String> = BTreeSet::new();
        for &g in GROUPS {
            let in_group: Vec<&Entry> = entries.values().filter(|(a, _)| a.group == g).map(|(_, e)| e).collect();
            let mut count: BTreeMap<&str, usize> = BTreeMap::new();
            for e in &in_group {
                *count.entry(e.class_name.as_str()).or_default() += 1;
            }
            let mut taken = BTreeSet::new();
            for e in &in_group {
                let base = pascal(&e.class_name);
                let name = if count[e.class_name.as_str()] > 1 { format!("{}{base}", pascal(&e.prefix)) } else { base };
                if !taken.insert(name.clone()) {
                    return Err(format!("type name collision {name} in group {g}").into());
                }
                type_names.insert(e.name.clone(), name);
            }
            // A marker named like another marker's view wrapper (`SheetView`
            // vs `Sheet` + `View`, `WorkbookView` vs `Workbook` + `View`)
            // would collide with it: such a marker gets an `Element` suffix.
            //
            // The rule depends on the allowlist: adding `x:CT_Foo` renames an
            // already public `FooView` marker. So the renamed markers are
            // pinned in `ELEMENT_SUFFIXED`, and any change (a new rename or a
            // dropped one) fails codegen until the list is updated on purpose
            // (PR #53 review m7). The rule looks within one group only; a
            // collision across groups shows up as a rustc error.
            let group_names: BTreeSet<String> =
                in_group.iter().map(|e| type_names[&e.name].clone()).collect();
            for e in &in_group {
                let name = type_names[&e.name].clone();
                let clashes = ["View", "ViewMut"].iter().any(|suf| {
                    name.strip_suffix(suf).is_some_and(|m| !m.is_empty() && group_names.contains(m))
                });
                if clashes {
                    let renamed = format!("{name}Element");
                    taken.remove(&name);
                    if !taken.insert(renamed.clone()) {
                        return Err(format!("type name collision {renamed} in group {g}").into());
                    }
                    type_names.insert(e.name.clone(), renamed.clone());
                    suffixed.insert(format!("{g}::{renamed}"));
                }
            }
            // enums referenced by the group's entries
            let mut used: BTreeSet<(usize, usize)> = BTreeSet::new();
            for e in &in_group {
                if !e.attrs_incomplete {
                    used.extend(e.attrs.iter().filter_map(|a| match a.ty {
                        Ty::Enum(f, i) => Some((f, i)),
                        Ty::Simple(_) => None,
                    }));
                }
                if let ContentModel::Text(Ty::Enum(f, i)) = e.content {
                    used.insert((f, i));
                }
            }
            let mut by_name: BTreeMap<String, usize> = BTreeMap::new();
            for &at in &used {
                *by_name.entry(model.enum_at(at).name.clone()).or_default() += 1;
            }
            for &at in &used {
                let en = model.enum_at(at);
                let mut name = pascal(&en.name);
                if by_name[&en.name] > 1 || taken.contains(&name) {
                    let p = en.ty.split(':').next().unwrap_or_default();
                    name = format!("{}{name}", pascal(p));
                }
                if !taken.insert(name.clone()) {
                    return Err(format!("enum name collision {name} in group {g}").into());
                }
                enum_names.insert((g, at), name);
            }
        }
        let pinned: BTreeSet<String> = ELEMENT_SUFFIXED.iter().map(|s| (*s).to_owned()).collect();
        if suffixed != pinned {
            return Err(format!(
                "the `Element` suffix rule now renames {suffixed:?}, but ELEMENT_SUFFIXED pins {pinned:?}: \
                 a public marker name changes; update ELEMENT_SUFFIXED in xtask/src/emit.rs if intended"
            )
            .into());
        }
        Ok(Ctx { model, entries, type_names, enum_names, unique_attrs })
    }

    fn ns_const(prefix: &str) -> String {
        if prefix.is_empty() { "\"\"".into() } else { format!("NS_{}", upper(prefix)) }
    }

    fn qname_expr(&self, prefixed: &str, used: &mut BTreeSet<String>) -> Option<String> {
        let (p, l) = prefixed.split_once(':')?;
        self.model.ns_of_prefix(p)?;
        used.insert(p.to_owned());
        Some(format!("ooxml_core::QName::new({}, {})", Self::ns_const(p), lit(l)))
    }

    fn attr_qname_expr(&self, ns: &str, prefix: &str, local: &str, used: &mut BTreeSet<String>) -> String {
        if ns.is_empty() {
            return format!("ooxml_core::QName::new(\"\", {})", lit(local));
        }
        used.insert(prefix.to_owned());
        format!("ooxml_core::QName::new({}, {})", Self::ns_const(prefix), lit(local))
    }

    fn type_path(&self, from_group: &str, sdk_name: &str) -> String {
        let (a, _) = &self.entries[sdk_name];
        let n = &self.type_names[sdk_name];
        if a.group == from_group { n.clone() } else { format!("super::{}::{n}", a.group) }
    }

    fn simple_type_expr(&self, group: &'static str, ty: &Ty) -> String {
        match ty {
            Ty::Simple(s) => format!("ooxml_core::SimpleType::{s}"),
            Ty::Enum(f, i) => match self.enum_names.get(&(group, (*f, *i))) {
                Some(n) => format!("ooxml_core::SimpleType::Enum(<{n} as ooxml_core::EnumType>::VALUES)"),
                None => "ooxml_core::SimpleType::String".into(),
            },
        }
    }

    fn ty_info(&self, group: &'static str, ty: &Ty) -> TyInfo {
        let s = |rust: &str, parse, format| TyInfo { rust: rust.into(), parse, format };
        match ty {
            Ty::Enum(f, i) => match self.enum_names.get(&(group, (*f, *i))) {
                Some(n) => s(n, None, Fmt::Enum),
                None => s("&'a str", None, Fmt::Str),
            },
            Ty::Simple(t) => match *t {
                "Boolean" => s("bool", Some("parse_bool"), Fmt::Static("format_bool")),
                "OnOff" => s("bool", Some("parse_on_off"), Fmt::Static("format_bool")),
                "TrueFalse" => s("bool", Some("parse_true_false"), Fmt::Static("format_true_false")),
                "UInt8" => s("u8", Some("parse_u8"), Fmt::With("with_u8")),
                "UInt16" => s("u16", Some("parse_u16"), Fmt::With("with_u16")),
                "UInt32" => s("u32", Some("parse_u32"), Fmt::With("with_u32")),
                "UInt64" => s("u64", Some("parse_u64"), Fmt::With("with_u64")),
                "Int8" => s("i8", Some("parse_i8"), Fmt::With("with_i8")),
                "Int16" => s("i16", Some("parse_i16"), Fmt::With("with_i16")),
                "Int32" => s("i32", Some("parse_i32"), Fmt::With("with_i32")),
                "Int64" | "Integer" => s("i64", Some("parse_i64"), Fmt::With("with_i64")),
                "Double" => s("f64", Some("parse_f64"), Fmt::Float(false)),
                "Single" => s("f32", Some("parse_f32"), Fmt::Float(true)),
                _ => s("&'a str", None, Fmt::Str),
            },
        }
    }

    fn slot_expr(&self, entry: &Entry, s: &LSlot, used: &mut BTreeSet<String>, diags: &mut Diagnostics) -> String {
        let mut names = Vec::new();
        for (q, _) in &s.names {
            if q == ANY {
                continue;
            }
            match self.qname_expr(q, used) {
                Some(e) => names.push(e),
                None => diags.push(format!("UnknownPrefix {}: child {q}", entry.name)),
            }
        }
        let wildcard = match s.any_ns.as_deref() {
            None => "None".to_owned(),
            Some(ns) => {
                let tns = self.model.tns(entry.file);
                let toks: Vec<&str> = ns.split_whitespace().collect();
                match toks.as_slice() {
                    ["##any"] | [] => "Some(ooxml_core::Wildcard::Any)".into(),
                    ["##other"] => format!("Some(ooxml_core::Wildcard::Other({}))", lit(tns)),
                    _ => {
                        let l: Vec<String> = toks
                            .iter()
                            .map(|t| match *t {
                                "##local" => lit(""),
                                "##targetNamespace" => lit(tns),
                                u => lit(u),
                            })
                            .collect();
                        format!("Some(ooxml_core::Wildcard::List(&[{}]))", l.join(", "))
                    }
                }
            }
        };
        let lim = |l: Option<u32>| l.map_or("None".into(), |v| format!("Some({v})"));
        format!(
            "ooxml_core::Slot {{ names: &[{}], wildcard: {wildcard}, max_each: {}, max_total: {} }}",
            names.join(", "),
            lim(s.max_each()),
            lim(s.total)
        )
    }

    fn content_expr(&self, group: &'static str, e: &Entry, used: &mut BTreeSet<String>, diags: &mut Diagnostics) -> String {
        match &e.content {
            ContentModel::Empty => "ooxml_core::Content::Empty".into(),
            ContentModel::Text(t) => format!("ooxml_core::Content::Text({})", self.simple_type_expr(group, t)),
            ContentModel::Slots(sl) => {
                let v: Vec<String> = sl.iter().map(|s| self.slot_expr(e, s, used, diags)).collect();
                format!("ooxml_core::Content::Slots(&[{}])", v.join(", "))
            }
            ContentModel::Unsupported { names, .. } => {
                let v: Vec<String> = names.iter().filter_map(|q| self.qname_expr(q, used)).collect();
                format!("ooxml_core::Content::Unsupported(&[{}])", v.join(", "))
            }
        }
    }

    /// Cardinality of child `q` (`x:c`): Some(true) = single, Some(false) =
    /// repeating, None = ambiguous or not insertable.
    fn child_single(e: &Entry, q: &str) -> Option<bool> {
        let ContentModel::Slots(sl) = &e.content else { return Some(false) };
        let hits: Vec<_> = sl.iter().filter_map(|s| s.names.iter().find(|(n, _)| n == q)).collect();
        match hits.as_slice() {
            [(_, lim)] => Some(*lim == Some(1)),
            _ => None,
        }
    }

    pub fn emit_group(&self, group: &'static str, diags: &mut Diagnostics) -> Res<String> {
        let mut used: BTreeSet<String> = BTreeSet::new();
        let mut body = String::new();
        let mut checks = String::new();
        let group_entries: Vec<(&Allowed, &Entry)> =
            self.entries.values().filter(|(a, _)| a.group == group).map(|(a, e)| (a, e)).collect();

        // enums
        for ((g, at), name) in &self.enum_names {
            if *g != group {
                continue;
            }
            let en = self.model.enum_at(*at);
            let vals = self.model.enum_values(*at);
            doc(&mut body, &format!("`{}` — {}.", en.ty, en.summary.as_deref().unwrap_or(&en.name)));
            let _ = writeln!(body, "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum {name} {{");
            let mut vnames = Names::new(&[]);
            let mut variants = Vec::new();
            for (v, n) in &vals {
                let vn = vnames.claim(&pascal(n.as_deref().unwrap_or(v)), "_");
                let _ = writeln!(body, "#[doc = {}] {vn},", lit(&format!(" `{v}`")));
                variants.push(vn);
            }
            body.push_str("}\n");
            let values: Vec<String> = vals.iter().map(|(v, _)| lit(v)).collect();
            let arms: Vec<String> = variants.iter().enumerate().map(|(i, v)| format!("{i} => Some(Self::{v}),")).collect();
            let _ = writeln!(
                body,
                "impl ooxml_core::EnumType for {name} {{
                    const VALUES: &'static [&'static str] = &[{}];
                    fn from_index(i: usize) -> Option<Self> {{ match i {{ {} _ => None }} }}
                    fn index(self) -> usize {{ self as usize }}
                }}",
                values.join(", "),
                arms.join(" ")
            );
        }

        for (allowed, e) in &group_entries {
            let ty = &self.type_names[&e.name];
            let qn = self.qname_expr(&format!("{}:{}", e.prefix, e.local), &mut used).ok_or_else(|| format!("{}: unknown prefix", e.name))?;
            // ---- marker ----
            let mut d = format!("`{}` — {}", e.name, e.summary.as_deref().unwrap_or(&e.class_name));
            match &e.content {
                ContentModel::Unsupported { reason, .. } => {
                    let _ = write!(d, "\n\nContent model unsupported for insertion ({reason}).");
                }
                ContentModel::Slots(sl) if crate::lower::has_ambiguous(sl) => {
                    d.push_str("\n\nSome child names appear in two slots; insert those with `insert_in_slot`.");
                }
                _ => {}
            }
            if e.attrs_incomplete {
                d.push_str("\n\nThe SDK base class is not in the schema data: attributes are incomplete and attribute writes are refused.");
            }
            doc(&mut body, &d);
            let _ = writeln!(body, "#[derive(Debug)]\npub enum {ty} {{}}");
            // attribute name constants
            let mut consts = String::new();
            let mut const_names: BTreeMap<(String, String), String> = BTreeMap::new();
            let mut cnames = Names::new(&[]);
            for a in &e.attrs {
                let base = if a.ns.is_empty() { format!("ATTR_{}", upper(&a.local)) } else { format!("ATTR_{}_{}", upper(&a.prefix), upper(&a.local)) };
                let c = cnames.claim(&base, "_");
                let _ = writeln!(
                    consts,
                    "#[doc = {}] pub const {c}: ooxml_core::QName = {};",
                    lit(&format!(" `{}{}{}`", a.prefix, if a.prefix.is_empty() { "" } else { ":" }, a.local)),
                    self.attr_qname_expr(&a.ns, &a.prefix, &a.local, &mut used)
                );
                const_names.insert((a.ns.clone(), a.local.clone()), c);
            }
            if !consts.is_empty() {
                let _ = writeln!(body, "impl {ty} {{ {consts} }}");
            }
            let attrs: Vec<String> = e
                .attrs
                .iter()
                .map(|a| {
                    format!(
                        "ooxml_core::AttrSpec {{ name: {ty}::{}, ty: {}, default: {} }}",
                        const_names[&(a.ns.clone(), a.local.clone())],
                        self.simple_type_expr(group, &a.ty),
                        a.default.as_ref().map_or("None".into(), |d| format!("Some({})", lit(d)))
                    )
                })
                .collect();
            let content = self.content_expr(group, e, &mut used, diags);
            let _ = writeln!(
                body,
                "impl ooxml_core::ElementSpec for {ty} {{
                    const QNAME: ooxml_core::QName = {qn};
                    const SDK_NAME: &'static str = {};
                    const ATTRS: &'static [ooxml_core::AttrSpec] = &[{}];
                    const CONTENT: ooxml_core::Content = {content};
                    {}
                }}",
                lit(&e.name),
                attrs.join(", "),
                if e.attrs_incomplete { "const ATTRS_INCOMPLETE: bool = true;" } else { "" }
            );
            let _ = writeln!(checks, "const _: () = ooxml_core::schema::assert_spec::<{ty}>();");

            // ---- ChildOf ----
            let children: Vec<&String> = e.child_names.iter().filter(|c| self.entries.contains_key(*c)).collect();
            for c in &children {
                let (ca, _) = &self.entries[c.as_str()];
                let cfg = if ca.group == group { String::new() } else { format!("#[cfg(all(feature = \"{group}\", feature = \"{}\"))]", ca.group) };
                let cp = self.type_path(group, c);
                let _ = writeln!(body, "{cfg} impl ooxml_core::ChildOf<{ty}> for {cp} {{}}");
                let _ = writeln!(
                    checks,
                    "{cfg} const _: () = ooxml_core::schema::assert_child::<{ty}, {cp}>();"
                );
            }

            // ---- Detachable / SameType (ADR-0002 note "detach/insert") ----
            // Only entries opted in with `[detach]`; SameType only between
            // them (the reflexive case is a blanket impl in core).
            if allowed.detach {
                // An element prefix that does not resolve is an error: a
                // uniqueness declaration must never drop out silently.
                let list: Vec<String> = self
                    .unique_attrs
                    .iter()
                    .map(|(el, (ans, ap, al), def)| {
                        let eq = self.qname_expr(el, &mut used).ok_or_else(|| format!("unique_attrs: element {el}: unknown prefix"))?;
                        let aq = self.attr_qname_expr(ans, ap, al, &mut used);
                        Ok(format!(
                            "ooxml_core::UniqueAttr {{ element: {eq}, attr: {aq}, default: {} }}",
                            def.as_ref().map_or("None".into(), |d| format!("Some({})", lit(d)))
                        ))
                    })
                    .collect::<Res<_>>()?;
                let _ = writeln!(
                    body,
                    "impl ooxml_core::schema::__private::Sealed for {ty} {{}}\nimpl ooxml_core::Detachable for {ty} {{ const UNIQUE_ATTRS: &'static [ooxml_core::UniqueAttr] = &[{}]; }}",
                    list.join(", ")
                );
                let others = self.entries.iter().filter(|(_, (a, _))| a.detach).map(|(n, (a, oe))| (n.as_str(), a.group, oe));
                let (partners, mismatches) = same_type_partners(e, others);
                diags.lines.extend(mismatches);
                for (other, ogroup) in partners {
                    let cfg = if ogroup == group { String::new() } else { format!("#[cfg(all(feature = \"{group}\", feature = \"{ogroup}\"))]") };
                    let op = self.type_path(group, other);
                    let _ = writeln!(body, "{cfg} impl ooxml_core::SameType<{op}> for {ty} {{}}");
                }
            }

            // ---- views ----
            let view = format!("{ty}View");
            let view_mut = format!("{ty}ViewMut");
            let mut r = String::new();
            let mut w = String::new();
            let is_text = matches!(e.content, ContentModel::Text(_));
            let mut rn = Names::new(if is_text { &["text", "raw"] } else { &["raw"] });
            let mut wn = Names::new(if is_text { &["as_view", "set_text"] } else { &["as_view"] });
            if !e.attrs_incomplete {
                for a in &e.attrs {
                    let c = &const_names[&(a.ns.clone(), a.local.clone())];
                    let m = rn.claim(&snake(a.property.as_deref().unwrap_or(&a.local)), "_attr");
                    let qtext = format!("{}{}{}", a.prefix, if a.prefix.is_empty() { "" } else { ":" }, a.local);
                    let adoc = format!(
                        " `{qtext}`{}{}",
                        a.comment.as_deref().map(|c| format!(" — {c}")).unwrap_or_default(),
                        a.default.as_deref().map(|d| format!(" (default `{d}`)")).unwrap_or_default()
                    );
                    let info = self.ty_info(group, &a.ty);
                    let getter = match (&info.format, &a.default) {
                        (Fmt::Enum, None) => format!("pub fn {m}(&self) -> Option<ooxml_core::EnumValue<'a, {}>> {{ self.0.attr_enum({ty}::{c}) }}", info.rust),
                        (Fmt::Enum, Some(d)) => format!("pub fn {m}(&self) -> ooxml_core::EnumValue<'a, {}> {{ self.0.attr_enum_or({ty}::{c}, {}) }}", info.rust, lit(d)),
                        (Fmt::Str, None) => format!("pub fn {m}(&self) -> Option<&'a str> {{ self.0.attr({ty}::{c}) }}"),
                        (Fmt::Str, Some(d)) => format!("pub fn {m}(&self) -> &'a str {{ self.0.attr({ty}::{c}).unwrap_or({}) }}", lit(d)),
                        (_, None) => format!(
                            "pub fn {m}(&self) -> Result<Option<{}>, ooxml_core::AttrError> {{ self.0.attr_parsed({ty}::{c}, ooxml_core::value::{}) }}",
                            info.rust,
                            info.parse.unwrap()
                        ),
                        (_, Some(d)) => format!(
                            "pub fn {m}(&self) -> Result<{}, ooxml_core::AttrError> {{ self.0.attr_parsed_or({ty}::{c}, {}, ooxml_core::value::{}) }}",
                            info.rust,
                            lit(d),
                            info.parse.unwrap()
                        ),
                    };
                    let _ = writeln!(r, "#[doc = {}] {getter}", lit(&adoc));
                    if allowed.access == Access::Write {
                        let mb = m.trim_end_matches('_');
                        let sm = wn.claim(&format!("set_{mb}"), "_attr");
                        let rm = wn.claim(&format!("remove_{mb}"), "_attr");
                        let set = match &info.format {
                            Fmt::Str => format!("pub fn {sm}(&mut self, v: &str) -> Result<(), ooxml_core::Error> {{ self.0.set_attr({ty}::{c}, v) }}"),
                            Fmt::Static(f) => format!("pub fn {sm}(&mut self, v: {}) -> Result<(), ooxml_core::Error> {{ self.0.set_attr({ty}::{c}, ooxml_core::value::{f}(v)) }}", info.rust),
                            Fmt::With(f) => format!(
                                "pub fn {sm}(&mut self, v: {}) -> Result<(), ooxml_core::Error> {{ ooxml_core::value::{f}(v, |s| self.0.set_attr({ty}::{c}, s)) }}",
                                info.rust
                            ),
                            Fmt::Float(single) => format!(
                                "pub fn {sm}(&mut self, v: {}) -> Result<(), ooxml_core::Error> {{ self.0.set_attr({ty}::{c}, &ooxml_core::value::format_f64({})) }}",
                                info.rust,
                                if *single { "f64::from(v)" } else { "v" }
                            ),
                            Fmt::Enum => format!(
                                "pub fn {sm}(&mut self, v: {}) -> Result<(), ooxml_core::Error> {{ self.0.set_attr({ty}::{c}, ooxml_core::EnumType::as_str(v)) }}",
                                info.rust
                            ),
                        };
                        let _ = writeln!(w, "#[doc = {}] {set}", lit(&format!(" Sets{adoc}")));
                        let _ = writeln!(
                            w,
                            "#[doc = {}] pub fn {rm}(&mut self) -> Result<bool, ooxml_core::Error> {{ self.0.remove_attr({ty}::{c}) }}",
                            lit(&format!(" Removes `{qtext}`."))
                        );
                    }
                }
            }
            for c in &children {
                let (ca, ce) = &self.entries[c.as_str()];
                let cfg = if ca.group == group { String::new() } else { format!("#[cfg(feature = \"{}\")]", ca.group) };
                let cp = self.type_path(group, c);
                let cv = format!("{cp}View");
                let base = snake(e.child_props.get(c.as_str()).map_or(ce.class_name.as_str(), String::as_str));
                let cq = format!("{}:{}", ce.prefix, ce.local);
                let single = Self::child_single(e, &cq);
                if single == Some(true) {
                    let m = rn.claim(&base, "_child");
                    let _ = writeln!(r, "{cfg} #[doc = {}] pub fn {m}(&self) -> Option<{cv}<'a>> {{ self.0.child::<{cp}>().map({cv}) }}", lit(&format!(" First `{cq}` child.")));
                } else {
                    let m = rn.claim(&format!("{base}_iter"), "_child");
                    let _ = writeln!(
                        r,
                        "{cfg} #[doc = {}] pub fn {m}(&self) -> impl Iterator<Item = {cv}<'a>> {{ self.0.children::<{cp}>().map({cv}) }}",
                        lit(&format!(" `{cq}` children in document order."))
                    );
                }
                let insertable = matches!(e.content, ContentModel::Slots(_));
                if allowed.access == Access::Write && ca.access == Access::Write {
                    let cvm = format!("{cp}ViewMut");
                    if single == Some(true) {
                        let m = wn.claim(&format!("{base}_mut"), "_child");
                        let _ = writeln!(w, "{cfg} #[doc = {}] pub fn {m}(&mut self) -> Option<{cvm}<'_>> {{ self.0.child_mut::<{cp}>().map({cvm}) }}", lit(&format!(" First `{cq}` child, mutably.")));
                        if insertable {
                            let m = wn.claim(&format!("get_or_insert_{base}"), "_child");
                            let _ = writeln!(
                                w,
                                "{cfg} #[doc = {}] pub fn {m}(&mut self) -> Result<{cvm}<'_>, ooxml_core::Error> {{ self.0.get_or_insert::<{cp}>().map({cvm}) }}",
                                lit(&format!(" Existing `{cq}` child, or a new one in schema position."))
                            );
                        }
                    } else {
                        let m = wn.claim(&format!("{base}_mut_by"), "_child");
                        let _ = writeln!(
                            w,
                            "{cfg} #[doc = {}] pub fn {m}(&mut self, pred: impl FnMut(&ooxml_core::RawNode) -> bool) -> Option<{cvm}<'_>> {{ self.0.child_mut_by::<{cp}>(pred).map({cvm}) }}",
                            lit(&format!(" First `{cq}` child matching `pred`, mutably."))
                        );
                        if insertable && single.is_some() {
                            let m = wn.claim(&format!("insert_{base}_by"), "_child");
                            let _ = writeln!(
                                w,
                                "{cfg} #[doc = {}] pub fn {m}(&mut self, before: impl FnMut(usize, &ooxml_core::RawNode) -> bool) -> Result<{cvm}<'_>, ooxml_core::Error> {{ self.0.insert_by::<{cp}>(before).map({cvm}) }}",
                                lit(&format!(" Inserts a `{cq}` before the first slot sibling for which `before` is true (see `LensMut::insert_by`)."))
                            );
                            let m = wn.claim(&format!("insert_{base}"), "_child");
                            let _ = writeln!(
                                w,
                                "{cfg} #[doc = {}] pub fn {m}(&mut self) -> Result<{cvm}<'_>, ooxml_core::Error> {{ self.0.insert::<{cp}>().map({cvm}) }}",
                                lit(&format!(" Appends a `{cq}` at the end of its slot."))
                            );
                        }
                    }
                    let m = wn.claim(&format!("remove_{base}"), "_child");
                    let _ = writeln!(w, "{cfg} #[doc = {}] pub fn {m}(&mut self) -> bool {{ self.0.remove::<{cp}>() }}", lit(&format!(" Removes the first `{cq}` child.")));
                }
            }
            if matches!(e.content, ContentModel::Text(_)) {
                let _ = writeln!(r, "#[doc = \" Text content.\"] pub fn text(&self) -> std::borrow::Cow<'a, str> {{ self.0.text() }}");
                if allowed.access == Access::Write {
                    let _ = writeln!(
                        w,
                        "#[doc = \" Replaces the text (sets `xml:space=\\\"preserve\\\"` when needed).\"] pub fn set_text(&mut self, v: &str) -> Result<(), ooxml_core::Error> {{ self.0.set_text(v) }}"
                    );
                }
            }
            let _ = writeln!(r, "#[doc = \" The underlying raw node.\"] pub fn raw(&self) -> &'a ooxml_core::RawNode {{ self.0.raw() }}");
            doc(&mut body, &format!("Read-only view of [`{ty}`]."));
            let _ = writeln!(body, "#[derive(Clone, Debug)]\npub struct {view}<'a>(pub ooxml_core::Lens<'a, {ty}>);");
            let _ = writeln!(body, "impl<'a> {view}<'a> {{ {r} }}");
            if allowed.access == Access::Write {
                doc(&mut body, &format!("Mutable view of [`{ty}`]. Reads go through [`{view_mut}::as_view`]."));
                let _ = writeln!(body, "#[derive(Debug)]\npub struct {view_mut}<'a>(pub ooxml_core::LensMut<'a, {ty}>);");
                let _ = writeln!(
                    body,
                    "impl<'a> {view_mut}<'a> {{ #[doc = \" Read-only view of the same node.\"] pub fn as_view(&self) -> {view}<'_> {{ {view}(self.0.as_lens()) }} {w} }}"
                );
            }
        }

        let mut out = String::new();
        let _ = writeln!(out, "//! `{group}` feature group: generated schema markers, views and enums (ADR-0002 §3).");
        if !group_entries.is_empty() || !used.is_empty() {
            for p in &used {
                let uri = self.model.ns_of_prefix(p).unwrap_or_default();
                let _ = writeln!(out, "#[doc = {}] pub const {}: &str = {};", lit(&format!(" `{p}`: `{uri}`")), Self::ns_const(p), lit(uri));
            }
        }
        out.push_str(&body);
        out.push_str(&checks);
        format_rust(&out)
    }

    pub fn emit_mod(&self) -> Res<String> {
        let mut out = String::from("//! Generated modules, one per feature group (ADR-0002 §5).\n");
        for g in GROUPS {
            let _ = writeln!(out, "cfg_select! {{ feature = \"{g}\" => {{ pub mod {g}; }} _ => {{}} }}");
        }
        format_rust(&out)
    }
}

pub fn emit_parts(model: &Model<'_>) -> Res<String> {
    let opt = |v: &Option<String>| v.as_ref().map_or("None".into(), |s| format!("Some({})", lit(s)));
    let mut out = String::from("//! Part kinds from the Open XML SDK's `data/parts/*.json` (ADR-0002 §6).\n");
    out.push_str("use super::{PartChild, PartSpec};\n");
    out.push_str("/// Every part kind, sorted by name.\npub static PARTS: &[PartSpec] = &[\n");
    for p in &model.sdk.parts {
        let root_ns = p
            .root
            .as_ref()
            .and_then(|r| r.split_once(':'))
            .and_then(|(pre, _)| model.ns_of_prefix(pre))
            .map(String::from);
        let children: Vec<String> = p
            .children
            .iter()
            .map(|c| {
                format!(
                    "PartChild {{ name: {}, api_name: {}, multiple: {}, required: {} }}",
                    lit(&c.name),
                    lit(&c.api_name),
                    c.max_occurs_great_than_one,
                    c.min_occurs_is_non_zero
                )
            })
            .collect();
        let _ = writeln!(
            out,
            "PartSpec {{ name: {}, base: {}, content_type: {}, relationship_type: {}, target: {}, extension: {}, root_type: {}, root_namespace: {}, root_element: {}, general_path: {}, version: {}, children: &[{}] }},",
            lit(&p.name),
            lit(&p.base),
            opt(&p.content_type),
            opt(&p.relationship_type),
            opt(&p.target),
            opt(&p.extension),
            opt(&p.root),
            opt(&root_ns),
            opt(&p.root_element),
            opt(&p.paths.get("General").cloned()),
            opt(&p.version),
            children.join(", ")
        );
    }
    out.push_str("];\n");
    format_rust(&out)
}

pub fn format_rust(src: &str) -> Res<String> {
    let file = syn::parse_file(src).map_err(|e| {
        let dump = std::env::temp_dir().join("xtask-unparsable.rs");
        let _ = std::fs::write(&dump, src);
        format!("generated code does not parse: {e} (source written to {})", dump.display())
    })?;
    Ok(format!("{HEADER}{}", prettyplease::unparse(&file)))
}

/// What must agree for two entries to be `SameType`: resolved attributes
/// (name, type, default), attribute completeness, content model and children.
fn shape(e: &Entry) -> String {
    let attrs: Vec<_> = e.attrs.iter().map(|a| (&a.ns, &a.local, &a.ty, &a.default)).collect();
    format!("{attrs:?} {} {:?} {:?}", e.attrs_incomplete, e.content, e.child_names)
}

/// The `SameType` partners of `e` among `others` (SDK Name, group, entry):
/// a different entry with the same SDK complex type (the part of the SDK
/// Name before `/`) and the same [`shape`]. Same type but different shape
/// gives a `SameTypeMismatch` diagnostic and no impl.
fn same_type_partners<'o>(
    e: &Entry,
    others: impl Iterator<Item = (&'o str, &'static str, &'o Entry)>,
) -> (Vec<(&'o str, &'static str)>, Vec<String>) {
    let ct = e.name.split_once('/').map_or(e.name.as_str(), |(t, _)| t);
    let (mut partners, mut diags) = (Vec::new(), Vec::new());
    for (other, group, oe) in others {
        if other == e.name || other.split_once('/').map(|(t, _)| t) != Some(ct) {
            continue;
        }
        if shape(e) == shape(oe) {
            partners.push((other, group));
        } else {
            diags.push(format!("SameTypeMismatch {} {other}: same complex type, different resolved shape; no SameType", e.name));
        }
    }
    (partners, diags)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Attr;

    fn entry(name: &str, attr: &str) -> Entry {
        Entry {
            name: name.into(),
            file: 0,
            class_name: "C".into(),
            summary: None,
            prefix: "a".into(),
            local: name.rsplit(':').next().unwrap().into(),
            attrs: vec![Attr {
                ns: String::new(),
                local: attr.into(),
                prefix: String::new(),
                ty: Ty::Simple("String"),
                default: None,
                property: None,
                comment: None,
            }],
            attrs_incomplete: false,
            content: ContentModel::Empty,
            child_names: Default::default(),
            child_props: Default::default(),
        }
    }

    #[test]
    fn same_type_needs_same_complex_type_and_same_shape() {
        let rpr = entry("a:CT_T/a:rPr", "lang");
        let end = entry("a:CT_T/a:endParaRPr", "lang");
        let odd = entry("a:CT_T/a:defRPr", "other"); // same CT, different resolved attributes
        let ppr = entry("a:CT_P/a:pPr", "lang"); // same shape, other CT
        let all = [&rpr, &end, &odd, &ppr];
        let (partners, diags) = same_type_partners(&rpr, all.iter().map(|e| (e.name.as_str(), "dml", *e)));
        assert_eq!(partners, [("a:CT_T/a:endParaRPr", "dml")]);
        assert_eq!(diags.len(), 1);
        assert!(diags[0].starts_with("SameTypeMismatch a:CT_T/a:rPr a:CT_T/a:defRPr"), "{diags:?}");
    }
}

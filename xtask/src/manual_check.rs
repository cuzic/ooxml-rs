//! `cargo xtask manual-check <outdir>`: runs every format crate's manual-check
//! example and writes one bundle for the owner's check in Office.
//!
//! Layout of `<outdir>` (which must be absent or empty):
//!
//! - `xlsx/`, `pptx/`, `docx/`: each example's own outputs and `CHECKLIST.md`;
//! - `CHECKLIST.md`: an index of the formats, with each one's status;
//! - `expected.json`: content and recalculation expectations for LibreOffice CI;
//! - `manual-check.zip`: everything above, to send as one file.
//!
//! A format whose example fails is skipped with a message naming the command
//! and its exit status; the others still run, the index records the failure,
//! and the task exits non-zero at the end.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use zip::CompressionMethod;
use zip::write::{SimpleFileOptions, ZipWriter};

use crate::Res;

/// (folder, package, example target, application the owner opens the files in).
const FORMATS: &[(&str, &str, &str, &str)] = &[
    ("xlsx", "ooxml-xlsx", "xlsx_manual_check", "Excel"),
    ("pptx", "ooxml-pptx", "pptx_manual_check", "PowerPoint"),
    ("docx", "ooxml-docx", "docx_manual_check", "Word"),
];

const ZIP_NAME: &str = "manual-check.zip";

enum Outcome {
    Written,
    Failed(String),
}

/// Runs the bundle. Returns `Ok(false)` when any format failed.
pub fn run(root: &Path, out: &Path) -> Res<bool> {
    if out.exists() && std::fs::read_dir(out)?.next().is_some() {
        return Err(format!("{} exists and is not empty; choose a new directory", out.display()).into());
    }
    std::fs::create_dir_all(out)?;
    let out = out.canonicalize()?;
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());

    let mut outcomes = Vec::new();
    for &(dir, package, example, _) in FORMATS {
        let target = out.join(dir);
        eprintln!("manual-check: {dir}: cargo run -p {package} --example {example} -- {}", target.display());
        let status = Command::new(&cargo)
            .current_dir(root)
            .args(["run", "--quiet", "-p", package, "--example", example, "--"])
            .arg(&target)
            .status();
        let outcome = match status {
            Ok(s) if s.success() => Outcome::Written,
            Ok(s) => Outcome::Failed(format!("`cargo run -p {package} --example {example}` exited with {s}")),
            Err(e) => Outcome::Failed(format!("could not start cargo: {e}")),
        };
        if let Outcome::Failed(why) = &outcome {
            eprintln!("manual-check: skipping {dir}: {why} (see the output above)");
        }
        outcomes.push(outcome);
    }

    std::fs::write(out.join("CHECKLIST.md"), index(root, &out, &outcomes)?)?;
    std::fs::write(
        out.join("expected.json"),
        include_str!("../../tools/lo-check/expected.json"),
    )?;
    let files = write_zip(&out)?;
    eprintln!("manual-check: wrote {} ({files} files) and CHECKLIST.md to {}", ZIP_NAME, out.display());
    Ok(outcomes.iter().all(|o| matches!(o, Outcome::Written)))
}

fn index(root: &Path, out: &Path, outcomes: &[Outcome]) -> Res<String> {
    let rev = Command::new("git")
        .current_dir(root)
        .args(["rev-parse", "--short", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned());
    let mut md = String::new();
    writeln!(md, "# ooxml-rs manual check bundle\n")?;
    writeln!(
        md,
        "Generated by `cargo xtask manual-check <outdir>`{}. Each folder holds one format's \
         outputs and its own `CHECKLIST.md`; open the files in the application named below and \
         follow that checklist. `{ZIP_NAME}` contains everything in this folder.\n",
        rev.map(|r| format!(" at commit `{r}`")).unwrap_or_default()
    )?;
    writeln!(md, "| Format | Open in | Status | Checklist |")?;
    writeln!(md, "|---|---|---|---|")?;
    for (&(dir, package, example, app), outcome) in FORMATS.iter().zip(outcomes) {
        let (status, link) = match outcome {
            Outcome::Written if out.join(dir).join("CHECKLIST.md").is_file() => {
                ("written".to_owned(), format!("[`{dir}/CHECKLIST.md`]({dir}/CHECKLIST.md)"))
            }
            Outcome::Written => ("written (no CHECKLIST.md)".to_owned(), "—".to_owned()),
            Outcome::Failed(why) => (format!("**skipped**: {why}"), "—".to_owned()),
        };
        writeln!(md, "| {dir} (`{package}`, example `{example}`) | {app} | {status} | {link} |")?;
    }
    writeln!(
        md,
        "\nTo regenerate one format alone: `cargo run -p <package> --example <example> -- <dir>`. \
         The per-format checklists may still name the example's old target `manual_check`; it was \
         renamed to `<format>_manual_check` so the three no longer collide."
    )?;
    Ok(md)
}

/// Zips every file under `out` (sorted, deflated) into `out/ZIP_NAME`.
fn write_zip(out: &Path) -> Res<usize> {
    let mut files = Vec::new();
    collect(out, out, &mut files)?;
    files.retain(|p| p != Path::new(ZIP_NAME));
    files.sort();
    let mut zw = ZipWriter::new(std::fs::File::create(out.join(ZIP_NAME))?);
    let opts = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);
    for rel in &files {
        let name = rel.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/");
        zw.start_file(name, opts)?;
        zw.write_all(&std::fs::read(out.join(rel))?)?;
    }
    zw.finish()?;
    Ok(files.len())
}

fn collect(base: &Path, dir: &Path, files: &mut Vec<PathBuf>) -> Res<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(base, &path, files)?;
        } else {
            files.push(path.strip_prefix(base)?.to_path_buf());
        }
    }
    Ok(())
}

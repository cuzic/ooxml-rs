#!/usr/bin/env python3
"""O3 recalculation oracle data (ADR-0003 §7.1, review R2-M2 / R2-m6).

Owner or CI job (needs LibreOffice; not available in the development
sandbox). Recalculates every `*.xlsx` in DIR with LibreOffice headless and
hard recalc (OOXMLRecalcMode = always, set in a throw-away profile), re-saves
it, reads every cell value of the re-saved file, and writes a TSV:

    # libreoffice<TAB><version>
    # generated<TAB><UTC time>
    <file name><TAB><fnv1a64 of the original file, hex><TAB><sheet>!<cell><TAB><t><TAB><value>

Usage (from the repository root):

    cargo run -p ooxml-xlsx --example o3_inputs -- /tmp/o3
    python3 -I spikes/xlsx/o3_recalc.py /tmp/o3 reference/fixtures/xlsx/o3/expected.tsv

The inputs are generated by ooxml-rs from committed fixtures; nothing in them
is executed. Only `zipfile` and `xml.etree` read the re-saved files.
"""
import datetime
import os
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zipfile

SML = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
R = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"
PR = "{http://schemas.openxmlformats.org/package/2006/relationships}"

XCU = """<?xml version="1.0" encoding="UTF-8"?>
<oor:items xmlns:oor="http://openoffice.org/2001/registry" xmlns:xs="http://www.w3.org/2001/XMLSchema" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">
<item oor:path="/org.openoffice.Office.Calc/Formula/Load"><prop oor:name="OOXMLRecalcMode" oor:op="fuse"><value>0</value></prop></item>
<item oor:path="/org.openoffice.Office.Calc/Formula/Load"><prop oor:name="ODFRecalcMode" oor:op="fuse"><value>0</value></prop></item>
</oor:items>
"""


def fnv1a(data):
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def soffice():
    for name in ("soffice", "libreoffice"):
        p = shutil.which(name)
        if p:
            return p
    sys.exit("LibreOffice (soffice) not found")


def version(exe):
    out = subprocess.run([exe, "--version"], capture_output=True, text=True, check=True)
    return out.stdout.strip()


def shared_strings(z):
    try:
        root = ET.fromstring(z.read("xl/sharedStrings.xml"))
    except KeyError:
        return []
    return ["".join(t.text or "" for t in si.iter(SML + "t")) for si in root.findall(SML + "si")]


def cell_values(path):
    """{sheet!cell: (t, value)} for every cell with a value."""
    z = zipfile.ZipFile(path)
    wb = ET.fromstring(z.read("xl/workbook.xml"))
    rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
    targets = {r.get("Id"): r.get("Target") for r in rels.findall(PR + "Relationship")}
    sst = shared_strings(z)
    out = {}
    for s in wb.find(SML + "sheets").findall(SML + "sheet"):
        target = targets[s.get(R + "id")].lstrip("/")
        part = target if target.startswith("xl/") else "xl/" + target
        root = ET.fromstring(z.read(part))
        for c in root.iter(SML + "c"):
            v = c.find(SML + "v")
            t = c.get("t", "n")
            if t == "inlineStr":
                val = "".join(x.text or "" for x in c.iter(SML + "t"))
            elif v is None:
                continue
            elif t == "s":
                val, t = sst[int(v.text)], "str"
            else:
                val = v.text or ""
            out[f"{s.get('name')}!{c.get('r')}"] = (t, val)
    return out


# Positive control (PR #21 review M2): the canary input has a deliberately
# wrong cached value; a real recalculation must produce this value.
CANARY_PREFIX = "o3_canary-"
CANARY_CELL, CANARY_VALUE = "Sheet1!B1", "2"


def main():
    src, dest = sys.argv[1], sys.argv[2]
    exe = soffice()
    ver = version(exe)
    want = os.environ.get("O3_LIBREOFFICE_VERSION")
    if want and want not in ver:
        sys.exit(f"soffice reports {ver!r}, expected version {want}")
    files = sorted(f for f in os.listdir(src) if f.endswith(".xlsx"))
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        profile = os.path.join(tmp, "profile")
        os.makedirs(os.path.join(profile, "user"))
        with open(os.path.join(profile, "user", "registrymodifications.xcu"), "w") as f:
            f.write(XCU)
        outdir = os.path.join(tmp, "out")
        done = {}
        for name in files:
            data = open(os.path.join(src, name), "rb").read()
            h = fnv1a(data)
            if h not in done:
                work = os.path.join(tmp, f"{h:016x}.xlsx")
                with open(work, "wb") as f:
                    f.write(data)
                subprocess.run(
                    [exe, f"-env:UserInstallation=file://{profile}", "--headless", "--convert-to",
                     "xlsx:Calc MS Excel 2007 XML", "--outdir", outdir, work],
                    check=True, capture_output=True, timeout=300,
                )
                done[h] = cell_values(os.path.join(outdir, f"{h:016x}.xlsx"))
            for cell, (t, val) in sorted(done[h].items()):
                rows.append(f"{name}\t{h:016x}\t{cell}\t{t}\t{val}")
    canaries = [r for r in rows if r.startswith(CANARY_PREFIX) and f"\t{CANARY_CELL}\t" in r]
    if not canaries or any(not r.endswith(f"\t{CANARY_VALUE}") for r in canaries):
        sys.exit(f"positive control failed: LibreOffice did not recalculate the canary ({canaries})")
    os.makedirs(os.path.dirname(os.path.abspath(dest)), exist_ok=True)
    with open(dest, "w", encoding="utf-8") as f:
        f.write(f"# libreoffice\t{ver}\n")
        f.write(f"# generated\t{datetime.datetime.now(datetime.timezone.utc).isoformat()}\n")
        f.write("# OOXMLRecalcMode\t0 (always), canary recalculated\n")
        for k in ("GITHUB_SHA", "LANG", "LC_ALL", "TZ", "O3_CARGO_LOCK_SHA256"):
            f.write(f"# {k}\t{os.environ.get(k, '')}\n")
        for r in rows:
            f.write(r.replace("\n", "\\n") + "\n")
    print(f"{len(files)} files ({len(done)} distinct), {len(rows)} values -> {dest}")


if __name__ == "__main__":
    main()
